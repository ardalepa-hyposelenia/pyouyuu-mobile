#Requires -Version 5.1
<#
.SYNOPSIS
    Task T-X01: Generates strongly-typed Constants (from contracts/constants.json)
    for Go (api), Kotlin (android), and TypeScript (web).
    Can be run from workspace/ or from any individual lane repository.
#>

param(
    [string]$ContractsDir = "",
    [string]$ApiDir = "",
    [string]$AndroidDir = "",
    [string]$WebDir = ""
)

$ErrorActionPreference = "Stop"
$ScriptDir = $PSScriptRoot
$RepoRoot = Split-Path -Parent $ScriptDir
$ParentRoot = Split-Path -Parent $RepoRoot

if (-not $ContractsDir) {
    if (Test-Path (Join-Path $RepoRoot "contracts\constants.json")) {
        $ContractsDir = Join-Path $RepoRoot "contracts"
    } elseif (Test-Path (Join-Path $ParentRoot "workspace\contracts\constants.json")) {
        $ContractsDir = Join-Path $ParentRoot "workspace\contracts"
    } else {
        throw "Could not locate contracts/constants.json"
    }
}

if (-not $ApiDir)     { $ApiDir     = Join-Path $ParentRoot "api" }
if (-not $AndroidDir) { $AndroidDir = Join-Path $ParentRoot "android" }
if (-not $WebDir)     { $WebDir     = Join-Path $ParentRoot "web" }

$ConstantsJsonPath = Join-Path $ContractsDir "constants.json"
$ConstantsDoc = Get-Content -Raw -Path $ConstantsJsonPath | ConvertFrom-Json
$Version = $ConstantsDoc.version
$Constants = $ConstantsDoc.constants

# ==============================================================================
# 1. GO CODEGEN (api/internal/constants/constants.gen.go)
# ==============================================================================
if (Test-Path $ApiDir) {
    $GoConstDir = Join-Path $ApiDir "internal\constants"
    New-Item -ItemType Directory -Force -Path $GoConstDir | Out-Null
    $GoOut = Join-Path $GoConstDir "constants.gen.go"

    $goLines = @(
        "// Code generated by scripts/generate-contracts.ps1 from contracts/constants.json (v$Version). DO NOT EDIT.",
        "package constants",
        "",
        "const ("
    )

    foreach ($prop in $Constants.PSObject.Properties) {
        $name = $prop.Name
        $item = $prop.Value
        $desc = $item.description
        $src  = $item.source
        $goLines += "`t// $name - $desc (Source: $src)"
        switch ($item.type) {
            "string" {
                $escaped = $item.value.Replace('\', '\\').Replace('"', '\"')
                $goLines += "`t$name = `"$escaped`""
            }
            "int" {
                if ($null -ne $item.hex) {
                    $goLines += "`t$name = $($item.hex) // $($item.value)"
                } else {
                    $goLines += "`t$name = $($item.value)"
                }
            }
            "float" {
                $goLines += "`t$name = $($item.value)"
            }
        }
    }
    $goLines += ")"
    [System.IO.File]::WriteAllText($GoOut, ($goLines -join "`n") + "`n", (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "Generated Go constants -> $GoOut" -ForegroundColor Green
}

# ==============================================================================
# 2. KOTLIN CODEGEN (android/app/src/main/java/com/pyouyuu/app/core/constants/PyouyuuConstants.kt)
# ==============================================================================
if (Test-Path $AndroidDir) {
    $KtConstDir = Join-Path $AndroidDir "app\src\main\java\com\pyouyuu\app\core\constants"
    New-Item -ItemType Directory -Force -Path $KtConstDir | Out-Null
    $KtOut = Join-Path $KtConstDir "PyouyuuConstants.kt"

    $ktLines = @(
        "// Code generated by scripts/generate-contracts.ps1 from contracts/constants.json (v$Version). DO NOT EDIT.",
        "package com.pyouyuu.app.core.constants",
        "",
        "object PyouyuuConstants {"
    )

    foreach ($prop in $Constants.PSObject.Properties) {
        $name = $prop.Name
        $item = $prop.Value
        $desc = $item.description
        $src  = $item.source
        $ktLines += "    /** $desc (Source: $src) */"
        switch ($item.type) {
            "string" {
                $escaped = $item.value.Replace('\', '\\').Replace('"', '\"')
                $ktLines += "    const val ${name}: String = `"$escaped`""
            }
            "int" {
                if ($null -ne $item.hex) {
                    $ktLines += "    const val ${name}: Int = $($item.hex) // $($item.value)"
                } else {
                    $ktLines += "    const val ${name}: Int = $($item.value)"
                }
            }
            "float" {
                $ktLines += "    const val ${name}: Float = $($item.value)f"
            }
        }
    }
    $ktLines += "}"
    [System.IO.File]::WriteAllText($KtOut, ($ktLines -join "`n") + "`n", (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "Generated Kotlin constants -> $KtOut" -ForegroundColor Green
}

# ==============================================================================
# 3. TYPESCRIPT CODEGEN (web/src/generated/constants.ts)
# ==============================================================================
if (Test-Path $WebDir) {
    $TsGenDir = Join-Path $WebDir "src\generated"
    New-Item -ItemType Directory -Force -Path $TsGenDir | Out-Null
    $TsOut = Join-Path $TsGenDir "constants.ts"

    $tsLines = @(
        "// Code generated by scripts/generate-contracts.ps1 from contracts/constants.json (v$Version). DO NOT EDIT.",
        ""
    )

    $objEntries = @()
    foreach ($prop in $Constants.PSObject.Properties) {
        $name = $prop.Name
        $item = $prop.Value
        $desc = $item.description
        $src  = $item.source
        $tsLines += "/** $desc (Source: $src) */"
        switch ($item.type) {
            "string" {
                $escaped = $item.value.Replace('\', '\\').Replace("'", "\'")
                $tsLines += "export const $name = '$escaped' as const;"
                $objEntries += "  $name,"
            }
            "int" {
                if ($null -ne $item.hex) {
                    $tsLines += "export const $name = $($item.hex) as const; // $($item.value)"
                } else {
                    $tsLines += "export const $name = $($item.value) as const;"
                }
                $objEntries += "  $name,"
            }
            "float" {
                $tsLines += "export const $name = $($item.value) as const;"
                $objEntries += "  $name,"
            }
        }
    }

    $tsLines += ""
    $tsLines += "export const PYOUYUU_CONSTANTS = {"
    $tsLines += $objEntries
    $tsLines += "} as const;"
    [System.IO.File]::WriteAllText($TsOut, ($tsLines -join "`n") + "`n", (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "Generated TypeScript constants -> $TsOut" -ForegroundColor Green
}
